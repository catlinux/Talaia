#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.txt with the license text of every third-party
// component that ends up in a Talaia build: the Go modules linked into
// talaia-core, talaia-agent and talaiactl (Linux build) and the production
// packages of the web panel. The file ships in the agent package and in the
// core image, because BSD, MIT and OFL require the notices to travel with
// binary copies.
//
// Usage: node scripts/third-party-notices.mjs [--check]
//   --check  exit 1 if the committed file is out of date instead of writing it
//
// Needs go and pnpm on PATH and the web dependencies installed.
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = join(root, 'THIRD-PARTY-NOTICES.txt')
const goModules = ['core', 'agent', 'cli']
// pnpm lists typescript as a production package because i18next declares it as an
// optional peer dependency; it never reaches the built panel.
const notBundled = new Set(['typescript'])

// shell: true lets Windows resolve go.cmd and pnpm.cmd.
function run(cmd, args, cwd, env = {}) {
  return execFileSync(cmd, args, {
    cwd,
    encoding: 'utf8',
    shell: process.platform === 'win32',
    env: { ...process.env, ...env },
    maxBuffer: 64 * 1024 * 1024,
  })
}

function findFiles(dir, pattern) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((name) => pattern.test(name))
    .sort()
    .map((name) => join(dir, name))
}

function readNormalized(file) {
  return readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim()
}

function classify(text) {
  if (text.includes('Apache License')) return 'Apache-2.0'
  if (text.includes('Mozilla Public License')) return 'MPL-2.0'
  if (text.includes('SIL Open Font License')) return 'OFL-1.1'
  if (text.includes('Permission is hereby granted, free of charge')) return 'MIT'
  if (/Permission to use, copy, modify, and(\/or)? distribute/.test(text)) return 'ISC'
  if (/Neither the name|names of its/.test(text)) return 'BSD-3-Clause'
  if (text.includes('Redistribution and use in source and binary forms')) return 'BSD-2-Clause'
  return 'UNKNOWN'
}

function collectGo() {
  const seen = new Map()
  for (const mod of goModules) {
    const out = run(
      'go',
      // No spaces or shell metacharacters in the template: on Windows it goes through cmd.
      ['list', '-deps', '-f', '{{with.Module}}{{.Path}}@@{{.Version}}@@{{.Dir}}@@{{.Main}}{{end}}', './...'],
      join(root, mod),
      { GOOS: 'linux', GOARCH: 'amd64' },
    )
    for (const line of out.split(/\r?\n/)) {
      if (!line || line.startsWith('github.com/catlinux/')) continue
      const [path, version, dir, main] = line.split('@@')
      if (main === 'true') continue
      seen.set(path, { name: path, version, dir, url: `https://pkg.go.dev/${path}@${version}` })
    }
  }
  return [...seen.values()]
}

function collectWeb() {
  const json = JSON.parse(run('pnpm', ['licenses', 'list', '--prod', '--json'], join(root, 'web')))
  const items = []
  for (const list of Object.values(json)) {
    for (const pkg of list) {
      if (notBundled.has(pkg.name)) continue
      pkg.versions.forEach((version, i) => {
        items.push({
          name: pkg.name,
          version,
          dir: pkg.paths[i],
          license: pkg.license,
          url: pkg.homepage ?? `https://www.npmjs.com/package/${pkg.name}`,
        })
      })
    }
  }
  return items
}

function render(components) {
  const missing = []
  const blocks = components.map((c) => {
    const licenses = findFiles(c.dir, /^(LICEN[CS]E|COPYING)/i)
    const notices = findFiles(c.dir, /^NOTICE/i)
    if (licenses.length === 0) missing.push(`${c.name}@${c.version}`)
    const texts = [...licenses, ...notices].map(readNormalized)
    // npm packages declare their license; Go modules only ship the text.
    const id = c.license ?? (licenses.length ? classify(texts[0]) : 'UNKNOWN')
    return [`${c.name} ${c.version}`, `License: ${id}`, `Source: ${c.url}`, '', ...texts].join('\n')
  })
  if (missing.length) {
    throw new Error(`no license file found for: ${missing.join(', ')}`)
  }
  const header = [
    'Third-party notices for Talaia',
    '',
    'Talaia includes the third-party components listed below. Each one keeps its own',
    'license, reproduced here; none of them is covered by the Talaia license (see',
    'LICENSE). This file is generated by scripts/third-party-notices.mjs.',
  ].join('\n')
  const separator = '\n\n' + '='.repeat(78) + '\n\n'
  return header + separator + blocks.join(separator) + '\n'
}

const components = [
  ...collectGo().map((c) => ({ ...c, group: 'go' })),
  ...collectWeb().map((c) => ({ ...c, group: 'web' })),
].sort((a, b) => a.group.localeCompare(b.group) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const text = render(components)

if (process.argv.includes('--check')) {
  const current = existsSync(output) ? readFileSync(output, 'utf8').replace(/\r\n/g, '\n') : ''
  if (current !== text) {
    console.error('THIRD-PARTY-NOTICES.txt is out of date: run node scripts/third-party-notices.mjs')
    process.exit(1)
  }
  console.log(`THIRD-PARTY-NOTICES.txt is up to date (${components.length} components)`)
} else {
  writeFileSync(output, text)
  console.log(`wrote THIRD-PARTY-NOTICES.txt (${components.length} components)`)
}
