const loadedAt = new Date()

function minutesAgo(minutes: number): string {
  return new Date(loadedAt.getTime() - minutes * 60_000).toISOString()
}

function hoursAgo(hours: number): string {
  return new Date(loadedAt.getTime() - hours * 3_600_000).toISOString()
}

